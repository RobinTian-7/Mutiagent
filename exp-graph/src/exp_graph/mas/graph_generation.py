# 【职责】共享的机械载荷（语法/预算/技能证据）；行为性字段由各 builder 自己写。
def _base_prompt_payload(
    *,
    request: PlannerRequest,
    skills: list[SkillCard],
    avoid_skills: list[SkillCard] | None,
    options: GraphValidationOptions,
    num_candidates: int,
    include_failure_feedback: bool = False,
) -> dict[str, object]:
    negative_skills: list[SkillCard] = []
    seen_negative: set[str] = set()
    negative_sources = [*(avoid_skills or [])]
    if include_failure_feedback:
        negative_sources = [*skills, *negative_sources]
    for skill in negative_sources:
        if not (skill.failure_modes or skill.counterexamples or skill.risk_notes):
            continue
        if skill.skill_id in seen_negative:
            continue
        negative_skills.append(skill)
        seen_negative.add(skill.skill_id)
    payload: dict[str, object] = {
        "request": request.model_dump(mode="json"),
        "graph_constraints": options.model_dump(mode="json"),
        "num_candidates": num_candidates,
        "topology_program_language": dict(_TOPOLOGY_PROGRAM_LANGUAGE),
        "candidate_diversity_requirements": [
            "If num_candidates > 1, produce structurally different edge schedules rather than renaming the same graph.",
            "Vary the aggregation-point choice, fan-in pattern, or audit/repair edge placement when it helps the objective.",
            "Each candidate must independently satisfy graph_constraints after program expansion.",
        ],
        "skill_evidence": [
            _skill_context(skill, include_risks=not include_failure_feedback)
            for skill in skills[:6]
        ],
        # Keep the legacy key and contents when v2 feedback is disabled.
        "avoid_or_counterexample_skills": [
            _skill_context(skill) for skill in (avoid_skills or [])[:6]
        ],
        "skill_usage_rules": [
            "Use design_insights, structure_features, and operation_recommendations from skills as concrete design operations, not as structure names to copy blindly.",
            "Prioritize design_insights.operation_recommendations when deciding which edges, fan-in limits, aggregation points, audit/provenance paths, or condition buckets to preserve, mutate, avoid, or validate.",
            "If a skill includes organization_policy.protocol_spec, treat it as an executable reference edge schedule; preserve or deliberately improve its coverage and fan-in properties.",
            "Respect condition buckets in skill triggers; do not generalize a skill outside its n_agents or array_size bucket without evidence.",
            "Treat avoid_or_counterexample_skills as negative constraints; do not reproduce their edge schedules or failure patterns for the same condition bucket.",
            "In each candidate rationale, name the design insight or operation recommendation being preserved, mutated, avoided, or validated.",
        ],
        "required_json_shape": _required_json_shape(request.n_agents),
    }
    if include_failure_feedback:
        payload["negative_failure_context"] = _bounded_context_items(
            [_failure_skill_context(skill) for skill in negative_skills[:6]],
            max_chars=4_000,
        )
        rules = payload["skill_usage_rules"]
        assert isinstance(rules, list)
        rules.append(
            "Treat negative_failure_context as answer-free failure constraints; "
            "do not reproduce those structural failure patterns."
        )
    return payload


