def _scrub_failure_context(value: Any) -> Any:
    if isinstance(value, dict):
        return {
            str(key): _scrub_failure_context(item)
            for key, item in value.items()
            if str(key).lower() not in _FAILURE_CONTEXT_FORBIDDEN_KEYS
        }
    if isinstance(value, (list, tuple)):
        return [_scrub_failure_context(item) for item in value]
    return value


def _bounded_context_items(
    items: list[dict[str, object]],
    *,
    max_chars: int,
) -> list[dict[str, object]]:
    """Bound JSON context deterministically without truncating structures."""
    output: list[dict[str, object]] = []
    used = 2
    for item in items:
        encoded = json.dumps(item, ensure_ascii=True, sort_keys=True)
        if used + len(encoded) > max_chars:
            break
        output.append(item)
        used += len(encoded) + 1
    return output


# 【职责】宽松解析 JSON 对象：整体解析失败时用正则截取首个 {...} 再试。
def _loads_json_object(text: str) -> dict[str, Any]:
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", text, flags=re.DOTALL)
        if not match:
            raise
        data = json.loads(match.group(0))
    if not isinstance(data, dict):
        raise ValueError("expected JSON object")
    return data


def _mean(rows: list[dict[str, object]], key: str) -> float:
    values = [float(row[key]) for row in rows if row.get(key) is not None]
    return fmean(values) if values else 0.0


# 【职责】把聚合探针行折算成"越高越好"的目标分。
# - accuracy_max 模式直接取 -rmse；否则按目标(accuracy_first/budget_first/
#   balanced)以不同权重扣减 rmse/消息数/token 成本
def _objective_score(
    row: dict[str, object],
    *,
    score_mode: str = "objective",
) -> float:
    rmse = float(row.get("mean_rmse", 0.0))
    if score_mode == "accuracy_max":
        return -rmse
    objective = str(row.get("objective", "balanced"))
    messages = float(row.get("mean_messages", 0.0))
    tokens = float(row.get("mean_token_cost", 0.0))
    exact = float(row.get("exact_match_rate", 0.0))
    if objective == "budget_first":
        return exact - 0.4 * rmse - 0.02 * messages - 0.0001 * tokens
    if objective == "accuracy_first":
        return exact - rmse - 0.002 * messages - 0.00001 * tokens
    return exact - 0.7 * rmse - 0.01 * messages - 0.00005 * tokens


def _write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
