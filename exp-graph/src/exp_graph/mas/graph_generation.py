# 【职责】fake 平台的确定性假候选(树/星/链/成对+星轮换)，供无 LLM 测试路径。
def _fake_graph_candidates(
    request: PlannerRequest,
    count: int,
) -> list[GeneratedGraphPlan]:
    builders = [_fake_tree_graph, _fake_star_graph, _fake_chain_graph, _fake_pair_star_graph]
    graphs = []
    for idx in range(count):
        graph = builders[idx % len(builders)](request.n_agents, idx)
        graphs.append(graph)
    return graphs


def _fake_tree_graph(n_agents: int, idx: int) -> GeneratedGraphPlan:
    steps: list[GeneratedGraphStep] = []
    stride = 1
    while stride < n_agents:
        edges = []
        block = stride * 2
        for start in range(0, n_agents, block):
            left = start + stride - 1
            right = min(start + block - 1, n_agents - 1)
            if left < n_agents and left != right:
                edges.append((left, right))
        if edges:
            steps.append(
                GeneratedGraphStep(
                    description=f"tree reduce stride {stride}",
                    edges=edges,
                    operator_hint="tree_reduce",
                )
            )
        stride *= 2
    return GeneratedGraphPlan(
        provenance="fake",
        candidate_id=f"candidate_{idx}",
        name=f"generated_tree_reduce_n{n_agents}",
        n_agents=n_agents,
        steps=steps,
        selected_primary=n_agents - 1,
        rationale="Sparse tree reduction generated by fake emperor.",
        fallback_topology="tree",
    )


def _fake_star_graph(n_agents: int, idx: int) -> GeneratedGraphPlan:
    sink = n_agents - 1
    return GeneratedGraphPlan(
        provenance="fake",
        candidate_id=f"candidate_{idx}",
        name=f"generated_star_sink_n{n_agents}",
        n_agents=n_agents,
        steps=[
            GeneratedGraphStep(
                description="star gather to final sink",
                edges=[(agent, sink) for agent in range(n_agents) if agent != sink],
                operator_hint="star_sink",
            )
        ],
        selected_primary=sink,
        rationale="Single-step sink gather generated by fake emperor.",
        fallback_topology="star",
    )


def _fake_chain_graph(n_agents: int, idx: int) -> GeneratedGraphPlan:
    return GeneratedGraphPlan(
        provenance="fake",
        candidate_id=f"candidate_{idx}",
        name=f"generated_chain_n{n_agents}",
        n_agents=n_agents,
        steps=[
            GeneratedGraphStep(
                description=f"chain hop {agent}",
                edges=[(agent, agent + 1)],
                operator_hint="peer_propagate",
            )
            for agent in range(max(0, n_agents - 1))
        ],
        selected_primary=n_agents - 1,
        rationale="Sequential chain generated by fake emperor.",
        fallback_topology="chain",
    )


def _fake_pair_star_graph(n_agents: int, idx: int) -> GeneratedGraphPlan:
    sink = n_agents - 1
    pair_edges = [
        (agent, min(agent + 1, sink))
        for agent in range(0, n_agents - 1, 2)
        if agent != min(agent + 1, sink)
    ]
    sink_edges = [
        (agent, sink)
        for agent in range(n_agents)
        if agent != sink and agent % 2 == 1
    ]
    steps = []
    if pair_edges:
        steps.append(
            GeneratedGraphStep(
                description="pairwise local exchange",
                edges=pair_edges,
                operator_hint="peer_propagate",
            )
        )
    if sink_edges:
        steps.append(
            GeneratedGraphStep(
                description="paired representatives gather to sink",
                edges=sink_edges,
                operator_hint="star_sink",
            )
        )
    return GeneratedGraphPlan(
        provenance="fake",
        candidate_id=f"candidate_{idx}",
        name=f"generated_pair_star_n{n_agents}",
        n_agents=n_agents,
        steps=steps,
        selected_primary=sink,
        rationale="Pairwise exchange followed by sink gather.",
        fallback_topology="explicit_temporal_dag",
    )


# 【职责】遮蔽文本中的已知 API key 值（环境变量值级别的扫描），防止写盘泄密。
def _scrub_secrets(text: str) -> str:
    import os

    scrubbed = text
    for env_name, value in os.environ.items():
        if not value or len(value) < 8:
            continue
        upper = env_name.upper()
        if any(tag in upper for tag in ("API_KEY", "APIKEY", "SECRET", "TOKEN")):
            scrubbed = scrubbed.replace(value, f"[REDACTED:{env_name}]")
    return scrubbed


