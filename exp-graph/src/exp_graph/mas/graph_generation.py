GraphSearchMode = Literal["single", "topk"]


# 【职责】皇帝生成的"一轮同时通信"：同一步内所有边同时发射。
# - edges: [src, dst] 有向边列表，dst 在上一步结束后收到 src 的当前作答产物
# - operator_hint: 该步操作子提示；instruction: 面向接收方的角色指令(可选)
class GeneratedGraphStep(BaseModel):
    """One simultaneous communication round generated by the emperor."""

    description: str = ""
    edges: list[tuple[int, int]] = Field(default_factory=list)
    operator_hint: str = "llm_generated"
    # 中文：M9——可选的面向接收方的角色指导，会随编译带入 spec；
    #   除非指令改写路径设置它，否则处处为 None。
    # M9: optional receiver-facing role guidance carried into the compiled
    # spec (None everywhere unless the instruction-rewrite path sets it).
    instruction: str | None = None

    # 【职责】把 edges 归一化为 (int, int) 元组列表；None→[]，非法形状抛错。
    @field_validator("edges", mode="before")
    @classmethod
    def normalize_edges(cls, value: object) -> list[tuple[int, int]]:
        if value is None:
            return []
        if not isinstance(value, list):
            raise ValueError("edges must be a list")
        edges: list[tuple[int, int]] = []
        for item in value:
            if not isinstance(item, (list, tuple)) or len(item) != 2:
                raise ValueError("each edge must be a [src, dst] pair")
            edges.append((int(item[0]), int(item[1])))
        return edges


# 【职责】皇帝产出的结构化 JSON 拓扑候选(DAG)——一份完整的时序通信方案。
# - steps: 逐轮边表；selected_primary: 最终答案持有者(汇点)；rationale: 设计理由
# - fallback_topology: 兜底拓扑名；expected_tradeoff: 预期精度/成本权衡
class GeneratedGraphPlan(BaseModel):
    """Structured JSON topology candidate produced by the emperor."""

    candidate_id: str = "candidate_0"
    name: str = "generated_temporal_dag"
    graph_type: str = "temporal_dag"
    n_agents: int
    steps: list[GeneratedGraphStep] = Field(default_factory=list)
    selected_primary: int | None = None
    rationale: str = ""
    expected_tradeoff: dict[str, object] = Field(default_factory=dict)
    fallback_topology: str | None = None
    # A compact LLM-authored source program. Once admitted, ``steps`` contains
    # its finite expansion so every downstream graph path remains unchanged.
    program: TopologyProgram | None = None
    program_compilation: dict[str, object] = Field(default_factory=dict)
    program_compilation_error: str | None = None
    # 中文：M14——带 DIRECT 槽位证据的技能种子重放(历史结构)按原样部署(Preserve)；
    #   只有迁移进无证据领域时才改写其指令(Modify)。默认 True=沿用历史行为。
    # M14: seeded replays from skills with DIRECT slot evidence are deployed
    # verbatim (Preserve); only transfers into unevidenced territory get
    # their instructions rewritten (Modify). Default True = historical.
    allow_instruction_rewrite: bool = True
    # 中文：M20——该结构在训练集上已验证(VERIFIED)的逐步指令集(由部署视图盖章)；
    #   Modify 改写以它为锚，而非从零重掷风格。None=沿用历史提示词。
    # M20: a train-VERIFIED per-step instruction set for this structure
    # (stamped by the deployment view); the Modify rewrite anchors on it
    # instead of re-rolling style from scratch. None = historical prompt.
    instruction_exemplar: list[str] | None = None
    # Filled only for a candidate reconstructed from a persisted SkillCard.
    # It makes hot-start reuse auditable without exposing skill ids to the LLM.
    source_skill_id: str | None = None
    # 中文：结构来源：llm_generated=皇帝新生成 / skill_replay=技能卡重放 / fake=离线
    #   假候选。clean GraphGen 只允许前两者的产物入库。解析层强制覆盖模型自称的值。
    # Structural provenance: llm_generated / skill_replay / fake. The parser
    # force-stamps this; a model-claimed value is never trusted.
    provenance: str = "llm_generated"


# 【职责】生成拓扑候选的硬约束：步数/消息数/汇入边数上限与修复次数等。
class GraphValidationOptions(BaseModel):
    """Hard constraints for generated topology candidates."""

    n_agents: int
    max_steps: int = 4
    max_messages: int = 32
    max_receiver_fan_in: int = 4
    repair_attempts: int = 1
    # 中文：D2(可选开启)——要求完整信息覆盖。谓词由 information_goal 决定：
    #   sink=所有 agent 沿时序可达 selected_primary；all_agents=每个 agent 都必须
    #   获得全部 source 信息。默认关闭 -> CF/既有行为逐字节不变；masbench(Silo) 开启。
    # D2 (opt-in): require full information coverage. The predicate follows
    # ``information_goal``: sink = every agent temporally reaches
    # selected_primary; all_agents = EVERY agent ends with every source's
    # information. Default OFF -> CF/existing behaviour byte-identical.
    require_full_sink_coverage: bool = False
    # 中文：信息目标：决定覆盖校验/修复谓词与(经 masbench)评分语义。
    # Information goal: selects the coverage predicate for validation/repair.
    information_goal: InformationGoal = "sink"


