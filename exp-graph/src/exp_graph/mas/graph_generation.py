def _fake_pair_star_graph(n_agents: int, idx: int) -> GeneratedGraphPlan:
    sink = n_agents - 1
    pair_edges = [
        (agent, min(agent + 1, sink))
        for agent in range(0, n_agents - 1, 2)
        if agent != min(agent + 1, sink)
    ]
    sink_edges = [
        (agent, sink)
        for agent in range(n_agents)
        if agent != sink and agent % 2 == 1
    ]
    steps = []
    if pair_edges:
        steps.append(
            GeneratedGraphStep(
                description="pairwise local exchange",
                edges=pair_edges,
                operator_hint="peer_propagate",
            )
        )
    if sink_edges:
        steps.append(
            GeneratedGraphStep(
                description="paired representatives gather to sink",
                edges=sink_edges,
                operator_hint="star_sink",
            )
        )
    return GeneratedGraphPlan(
        candidate_id=f"candidate_{idx}",
        name=f"generated_pair_star_n{n_agents}",
        n_agents=n_agents,
        steps=steps,
        selected_primary=sink,
        rationale="Pairwise exchange followed by sink gather.",
        fallback_topology="one_peer_exponential_dag_star",
    )


