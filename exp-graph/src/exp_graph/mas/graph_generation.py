def _format_graph_candidates(
    records: list[GraphCandidateRecord],
    selected: GraphCandidateRecord | None,
    fallback_reason: str | None,
) -> str:
    lines = ["# Generated Graph Candidates", ""]
    if fallback_reason:
        lines.extend(["fallback_reason:", f"  {fallback_reason}", ""])
    lines.append(f"selected_candidate_id: {selected.candidate_id if selected else 'none'}")
    lines.append("")
    for record in records:
        lines.extend(
            [
                f"## {record.candidate_id}",
                "",
                f"status: {record.status}",
                f"steps: {record.protocol_steps}",
                f"messages: {record.protocol_messages}",
                f"selected_primary: {record.selected_primary}",
                f"objective_score: {record.objective_score}",
                f"score_mode: {record.score_mode}",
                f"topology_equivalence_hash: {record.topology_equivalence_hash}",
                f"duplicate_of_candidate_id: {record.duplicate_of_candidate_id}",
                "",
            ]
        )
        if record.validation_errors:
            lines.append("validation_errors:")
            lines.extend(f"- {item}" for item in record.validation_errors)
            lines.append("")
        if record.repair_notes:
            lines.append("repair_notes:")
            lines.extend(f"- {item}" for item in record.repair_notes)
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _duplicate_equivalent_groups(
    records: list[GraphCandidateRecord],
) -> list[dict[str, object]]:
    grouped: dict[str, list[GraphCandidateRecord]] = {}
    for record in records:
        if record.topology_equivalence_hash:
            grouped.setdefault(record.topology_equivalence_hash, []).append(record)
    groups = []
    for topology_hash, items in sorted(grouped.items()):
        duplicates = [
            item
            for item in items
            if item.status == "duplicate_equivalent_topology"
        ]
        if not duplicates:
            continue
        kept = next(
            (item.duplicate_of_candidate_id for item in duplicates if item.duplicate_of_candidate_id),
            None,
        )
        groups.append(
            {
                "topology_equivalence_hash": topology_hash,
                "kept_candidate_id": kept,
                "duplicate_candidate_ids": [item.candidate_id for item in duplicates],
            }
        )
    return groups


def _top_k_records(
    records: list[GraphCandidateRecord],
    top_k: int,
) -> list[GraphCandidateRecord]:
    selectable = [
        record
        for record in records
        if record.status in {"selected", "evaluated", "valid", "repaired"}
    ]
    selectable.sort(
        key=lambda record: record.objective_score
        if record.objective_score is not None
        else float("-inf"),
        reverse=True,
    )
    return selectable[: max(1, top_k)]


def _add_reachability_warnings(graph: GeneratedGraphPlan, warnings: list[str]) -> None:
    selected = graph.selected_primary
    if selected is None:
        return
    reachable: dict[int, set[int]] = {
        agent: {agent} for agent in range(graph.n_agents)
    }
    for step in graph.steps:
        updates = {agent: set(values) for agent, values in reachable.items()}
        for src, dst in step.edges:
            if src not in reachable or dst not in updates:
                continue
            updates[dst].update(reachable.get(src, {src}))
        reachable = updates
    missing = sorted(set(range(graph.n_agents)) - reachable.get(selected, set()))
    if missing:
        warnings.append(
            f"agents without temporal path to selected_primary {selected}: {missing}"
        )


