    selected_candidate_id: str | None = None
    fallback_reason: str | None = None
    raw_responses: list[str] = Field(default_factory=list)
    # 中文：架构师审计：脱敏后的完整渲染提示词及其 sha256、最终选择原因。
    # Architect audit: the sanitized rendered prompt, its sha256, and the
    # final selection reason.
    architect_prompt: str | None = None
    architect_prompt_sha256: str | None = None
    selection_reason: str | None = None
    information_goal: InformationGoal = "sink"


