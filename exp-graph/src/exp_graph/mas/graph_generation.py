def _generate_graph_candidates(
    *,
    request: PlannerRequest,
    runtime: MASRuntimeConfig,
    skill_bank: SkillBank,
    options: GraphValidationOptions,
    llm_client: LLMClient | None,
    task_brief: str | None = None,
) -> tuple[list[GeneratedGraphPlan], list[str]]:
    count = max(1, runtime.num_graph_candidates)
    positive_skills = skill_bank.retrieve(request)
    seeded = _skill_seeded_graph_candidates(
        request=request,
        skills=positive_skills,
    )
    remaining_count = max(0, count - len(seeded))
    emperor_llm = resolve_role_llm_config(runtime, "emperor")
    if emperor_llm.platform == "fake":
        return [*seeded, *_fake_graph_candidates(request, remaining_count)], []
    if remaining_count == 0:
        return seeded, []
    client = llm_client or create_role_llm_client(runtime, "emperor")
    prompt = build_free_graph_prompt(
        request=request,
        skills=positive_skills,
        avoid_skills=skill_bank.retrieve_avoid(request),
        options=options,
        num_candidates=remaining_count,
        task_brief=task_brief,
    )
    response = client.complete(
        prompt,
        model_name=emperor_llm.model_name,
        temperature=emperor_llm.temperature,
    )
    candidates = parse_graph_candidates_response(
        response.text,
        n_agents=request.n_agents,
        expected_count=remaining_count,
    )
    return [*seeded, *candidates], [response.text]


def _skill_seeded_graph_candidates(
    *,
    request: PlannerRequest,
    skills: list[SkillCard],
) -> list[GeneratedGraphPlan]:
    graphs: list[GeneratedGraphPlan] = []
    seen: set[str] = set()
    for skill in skills[:6]:
        spec_data = skill.organization_policy.get("protocol_spec")
        if not isinstance(spec_data, dict) or not spec_data.get("steps"):
            continue
        try:
            spec = ProtocolGraphSpec.model_validate(spec_data)
        except Exception:
            continue
        if spec.n_agents != request.n_agents:
            continue
        graph = _graph_from_skill_protocol(skill, spec)
        digest = fingerprint_protocol_spec(spec).topology_equivalence_hash
        if digest in seen:
            continue
        seen.add(digest)
        graphs.append(graph)
        if len(graphs) >= 3:
            break
    return graphs


def _graph_from_skill_protocol(
    skill: SkillCard,
    spec: ProtocolGraphSpec,
) -> GeneratedGraphPlan:
    selected = spec.metadata.get("selected_primary")
    return GeneratedGraphPlan(
        candidate_id=f"skill_{_safe_candidate_id(skill.skill_id)}",
        name=spec.name or _safe_candidate_id(skill.skill_id),
        graph_type=str(spec.metadata.get("graph_type") or "temporal_dag"),
        n_agents=spec.n_agents,
        selected_primary=_optional_int(selected),
        steps=[
            GeneratedGraphStep(
                description=step.description,
                edges=step.transmissions,
                operator_hint=step.operator or "skill_replay",
            )
            for step in spec.steps
        ],
        rationale=f"Replay executable DAG stored in skill {skill.skill_id}.",
        expected_tradeoff=skill.expected_tradeoff,
        fallback_topology=(
            str(spec.metadata["fallback_topology"])
            if spec.metadata.get("fallback_topology") is not None
            else None
        ),
    )


def _safe_candidate_id(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]+", "_", value).strip("_")[:80] or "skill"


def _optional_int(value: object) -> int | None:
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def _graph_digest(graph: GeneratedGraphPlan) -> str:
    return json.dumps(
        [
            {
                "edges": step.edges,
                "operator_hint": step.operator_hint,
            }
            for step in graph.steps
        ],
        sort_keys=True,
        separators=(",", ":"),
    )


def parse_graph_candidates_response(
    text: str,
    *,
    n_agents: int,
    expected_count: int = 1,
) -> list[GeneratedGraphPlan]:
    """Parse an LLM response into generated graph candidates."""
    data = _loads_json_object(text)
    if "output_schema" in data or "required_json_shape" in data:
        raise ValueError("LLM echoed the graph schema instead of candidates")
    raw_candidates = data.get("candidates")
    if raw_candidates is None:
        raw_candidates = [data]
    if not isinstance(raw_candidates, list):
        raise ValueError("graph response must contain a candidates list")
    graphs = []
    for idx, item in enumerate(raw_candidates[: max(1, expected_count)]):
        if not isinstance(item, dict):
            raise ValueError("each graph candidate must be a JSON object")
        item.setdefault("candidate_id", f"candidate_{idx}")
        item.setdefault("n_agents", n_agents)
        item.setdefault("graph_type", "temporal_dag")
        graphs.append(GeneratedGraphPlan.model_validate(item))
    if not graphs:
        raise ValueError("no graph candidates returned")
    return graphs


def _validate_and_compile_candidates(
    graphs: list[GeneratedGraphPlan],
    options: GraphValidationOptions,
) -> list[_CandidateState]:
    states: list[_CandidateState] = []
    for generation_index, graph in enumerate(graphs):
        validation = validate_graph_plan(graph, options)
        repaired = graph
        repair_notes: list[str] = []
        status = "valid" if validation.valid else "rejected"
        if not validation.valid and options.repair_attempts > 0:
            repaired, repair_notes = repair_graph_plan(graph, options)
            repaired_validation = validate_graph_plan(repaired, options)
            validation = repaired_validation.model_copy(
                update={"repair_notes": repair_notes}
            )
            if repaired_validation.valid:
                status = "repaired"
        spec = None
        if validation.valid:
            spec = compile_generated_graph(repaired, options)
        protocol_steps = len(spec.steps) if spec else len(repaired.steps)
        protocol_messages = (
            sum(len(step.transmissions) for step in spec.steps)
            if spec
            else sum(len(step.edges) for step in repaired.steps)
        )
        topology_equivalence_hash = None
        exact_execution_hash = None
        canonical_temporal_edges: list[tuple[int, int, int]] = []
        if spec is not None:
            fingerprint = fingerprint_protocol_spec(spec)
            topology_equivalence_hash = fingerprint.topology_equivalence_hash
            exact_execution_hash = fingerprint.exact_execution_hash
            canonical_temporal_edges = fingerprint.canonical_temporal_edges
        states.append(
            _CandidateState(
                graph=repaired,
                spec=spec,
                generation_index=generation_index,
                record=GraphCandidateRecord(
                    candidate_id=repaired.candidate_id,
                    status=status,
                    graph_plan=repaired.model_dump(mode="json"),
                    protocol_spec=spec.model_dump(mode="json") if spec else None,
                    validation_errors=validation.errors,
                    validation_warnings=validation.warnings,
                    repair_notes=repair_notes,
                    protocol_steps=protocol_steps,
                    protocol_messages=protocol_messages,
                    selected_primary=repaired.selected_primary,
                    topology_equivalence_hash=topology_equivalence_hash,
                    exact_execution_hash=exact_execution_hash,
                    canonical_temporal_edges=canonical_temporal_edges,
                ),
            )
        )
    return states


def _dedupe_equivalent_candidates(
    states: list[_CandidateState],
) -> list[_CandidateState]:
    """Skip duplicate equivalent candidates before expensive probe evaluation."""
    grouped: dict[str, list[_CandidateState]] = {}
    representatives: list[_CandidateState] = []
    for state in states:
        key = state.record.topology_equivalence_hash
        if (
            key is None
            or state.spec is None
            or state.record.status not in {"valid", "repaired"}
        ):
            representatives.append(state)
            continue
        grouped.setdefault(key, []).append(state)

    for group in grouped.values():
        if len(group) == 1:
            representatives.append(group[0])
            continue
        representative = min(group, key=_candidate_dedup_sort_key)
        representatives.append(representative)
        for duplicate in group:
            if duplicate is representative:
                continue
            duplicate.record.status = "duplicate_equivalent_topology"
            duplicate.record.duplicate_of_candidate_id = representative.record.candidate_id
            duplicate.record.validation_warnings = [
                *duplicate.record.validation_warnings,
                (
                    "duplicate equivalent topology of "
                    f"{representative.record.candidate_id}; skipped probe evaluation"
                ),
            ]

    representatives.sort(key=lambda state: state.generation_index)
    return representatives


def _candidate_dedup_sort_key(state: _CandidateState) -> tuple[int, int, int, str, int]:
    return (
        0 if state.record.status == "valid" else 1,
        state.record.protocol_messages,
        state.record.protocol_steps,
        state.record.candidate_id,
        state.generation_index,
    )


def _select_candidate(
    valid_states: list[_CandidateState],
    runtime: MASRuntimeConfig,
) -> _CandidateState:
    """Pick the winning candidate, optionally applying the motif credit prior.

    ``valid_states`` arrives already in selection order: in ``topk`` mode it has
    been probe-evaluated and sorted by ``objective_score`` (higher = better); in
    the default single mode it is generation order, so ``valid_states[0]`` is
    today's first-valid pick.

    Default behavior (``use_motif_prior`` off, or ``motif_stats`` empty/None) is
    unchanged: the head of ``valid_states`` is returned, so selection stays
    byte-identical to before this prior existed.

    When ``use_motif_prior`` is on AND ``motif_stats`` is non-empty, this is the
    activation point for the Plan 3 Part G machinery: each valid compiled
    candidate is scored by :func:`exp_graph.mas.motifs.score_spec_by_motifs`
    (a lower-is-better predicted loss, transferred structurally from past
    evidence via shared motifs). Candidates are then stably re-sorted by that
    predicted loss ascending. The sort is stable over the incoming order, so the
    motif prior *blends* with any existing probe ``objective_score`` ordering:
    among candidates with an equal (or absent) motif signal, the prior
    probe-sorted / generation order is preserved as a deterministic tiebreak.
    Candidates that share no known motif key receive the +inf high-uncertainty
    sentinel and therefore never displace a candidate with real motif evidence;
    if *no* candidate has a known motif (all +inf), the order is unchanged.
    """
    if not runtime.use_motif_prior or not runtime.motif_stats:
        return valid_states[0]
    motif_stats = runtime.motif_stats
    scored: list[tuple[float, int, _CandidateState]] = []
    for rank, state in enumerate(valid_states):
        if state.spec is None:
            predicted = float("inf")
        else:
            predicted = score_spec_by_motifs(state.spec, motif_stats)
        # ``rank`` is the deterministic tiebreak that preserves the incoming
        # probe-sorted / generation order on equal (or +inf) motif scores.
        scored.append((predicted, rank, state))
    scored.sort(key=lambda item: (item[0], item[1]))
    return scored[0][2]


def _evaluate_candidates(
    *,
    states: list[_CandidateState],
    request: PlannerRequest,
    runtime: MASRuntimeConfig,
    seed: int,
    task_adapter: CountFrequencyTaskAdapter,
    output_dir: Path,
) -> None:
    # Probe-evaluation (topk mode only): execute each candidate on the
    # validation seeds and record an ``objective_score`` used to sort here. The
    # structural-motif credit prior (Plan 3 Part G) is applied separately and
    # opt-in in ``_select_candidate`` after this sort, so it blends with these
    # probe scores without changing the default-off ordering.
    output_dir.mkdir(parents=True, exist_ok=True)
    validation_seeds = runtime.graph_validation_seeds or [seed]
    for state in states:
        if state.spec is None:
            continue
        probe_rows: list[dict[str, object]] = []
        for probe_seed in validation_seeds:
            global_task = task_adapter.build_global_task(
                array_size=request.array_size or 64,
                value_min=runtime.value_min,
                value_max=runtime.value_max,
                seed=int(probe_seed),
            )
            soldier_llm = resolve_role_llm_config(runtime, "soldier")
            config = ProtocolRunnerConfig(
                topology_name=f"generated:{state.graph.name}",
                n_agents=request.n_agents,
                seed=int(probe_seed),
                model_name=soldier_llm.model_name,
                merge_mode=request.merge_mode,  # type: ignore[arg-type]
                init_mode=request.init_mode,  # type: ignore[arg-type]
                llm_provider=soldier_llm.platform,
                temperature=soldier_llm.temperature,
                json_retry_attempts=runtime.json_retry_attempts,
                allow_deterministic_repair=runtime.allow_deterministic_repair,
                max_parallel_agents=runtime.max_parallel_agents,
                trace_enabled=False,
                retain_traces=False,
                verbose_events=False,
                protocol_spec=state.spec,
                llm_role_summary=role_llm_summary(runtime),
            )
            result = ProtocolRunner(
                config=config,
                task_adapter=task_adapter,
                global_task=global_task,
                llm_client=(
                    create_role_llm_client(runtime, "soldier")
                    if _request_needs_soldier_llm(request)
                    else None
                ),
            ).run()
            row = _probe_row(result, request.objective.name)
            probe_rows.append(row)
            _write_json(
                output_dir / state.graph.candidate_id / f"seed_{probe_seed}.json",
                {
                    "candidate_id": state.graph.candidate_id,
                    "seed": probe_seed,
                    "summary": result.to_summary_dict(),
                    "objective_row": row,
                },
            )
        aggregate = _aggregate_probe_rows(probe_rows, request.objective.name)
        state.record.probe_scores = probe_rows
        state.record.objective_score = _objective_score(
            aggregate,
            score_mode=runtime.graph_candidate_score_mode,
        )
        state.record.score_mode = runtime.graph_candidate_score_mode
        if state.record.status in {"valid", "repaired"}:
            state.record.status = "evaluated"


def _request_needs_soldier_llm(request: PlannerRequest) -> bool:
    return request.init_mode == "llm_local_solve" or request.merge_mode != "deterministic"


def _probe_row(result: ProtocolExperimentResult, objective: str) -> dict[str, object]:
    summary = result.to_summary_dict()
    return {
        "objective": objective,
        "mean_rmse": float(summary["FinalRMSE"]),
        "exact_match_rate": 1.0 if summary["FinalExactMatch"] else 0.0,
        "mean_messages": float(summary["TotalMessages"]),
        "mean_model_calls": float(summary["TotalModelCalls"]),
        "mean_token_cost": float(
            summary["TotalPromptTokens"] + summary["TotalCompletionTokens"]
        ),
    }


def _aggregate_probe_rows(rows: list[dict[str, object]], objective: str) -> dict[str, object]:
    return {
        "objective": objective,
        "mean_rmse": _mean(rows, "mean_rmse"),
        "exact_match_rate": _mean(rows, "exact_match_rate"),
        "mean_messages": _mean(rows, "mean_messages"),
        "mean_model_calls": _mean(rows, "mean_model_calls"),
        "mean_token_cost": _mean(rows, "mean_token_cost"),
    }


