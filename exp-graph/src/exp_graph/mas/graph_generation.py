def plan_free_graph(
    *,
    request: PlannerRequest,
    runtime: MASRuntimeConfig,
    skill_bank: SkillBank,
    seed: int,
    task_adapter: CountFrequencyTaskAdapter,
    output_dir: Path,
    llm_client: LLMClient | None = None,
) -> FreeGraphPlanningResult:
    """Generate, validate, optionally probe-evaluate, and select a graph plan."""
    options = GraphValidationOptions(
        n_agents=request.n_agents,
        max_steps=runtime.graph_max_steps,
        max_messages=runtime.graph_max_messages,
        max_receiver_fan_in=runtime.graph_max_receiver_fan_in,
        repair_attempts=runtime.graph_repair_attempts,
    )
    # Pull a short task description from the adapter (duck-typed; CF adapters
    # don't define it -> None, and the CF prompt branch ignores it anyway) so the
    # emperor sees the ACTUAL task instead of hardcoded count_frequency notes.
    _describe = getattr(task_adapter, "describe_task", None)
    task_brief: str | None = None
    if callable(_describe):
        try:
            task_brief = _describe()
        except Exception:
            task_brief = None
    raw_responses: list[str] = []
    try:
        graphs, raw_responses = _generate_graph_candidates(
            request=request,
            runtime=runtime,
            skill_bank=skill_bank,
            options=options,
            llm_client=llm_client,
            task_brief=task_brief,
        )
        candidates = _validate_and_compile_candidates(graphs, options)
        representative_candidates = _dedupe_equivalent_candidates(candidates)
        valid_states = [
            state
            for state in representative_candidates
            if state.record.status in {"valid", "repaired"} and state.spec is not None
        ]
        if not valid_states:
            raise ValueError("no valid generated graph candidates")
        if runtime.graph_search_mode == "topk" and runtime.graph_validation_seeds:
            _evaluate_candidates(
                states=valid_states,
                request=request,
                runtime=runtime,
                seed=seed,
                task_adapter=task_adapter,
                output_dir=output_dir / "graph_candidate_eval",
            )
            valid_states.sort(
                key=lambda state: state.record.objective_score
                if state.record.objective_score is not None
                else float("-inf"),
                reverse=True,
            )
        selected = _select_candidate(valid_states, runtime)
        selected.record.status = "selected"
        plan = _mas_plan_from_graph(selected.graph, selected.spec)
        records = [state.record for state in candidates]
        _write_graph_artifacts(
            output_dir=output_dir,
            records=records,
            selected=selected.record,
            raw_responses=raw_responses,
            top_k=max(1, runtime.graph_top_k),
        )
        return FreeGraphPlanningResult(
            plan=plan,
            candidates=records,
            selected_candidate_id=selected.record.candidate_id,
            raw_responses=raw_responses,
        )
    except Exception as exc:
        fallback = _fallback_operator_plan(request, skill_bank, str(exc))
        result = FreeGraphPlanningResult(
            plan=fallback,
            fallback_reason=str(exc),
            raw_responses=raw_responses,
        )
        _write_graph_artifacts(
            output_dir=output_dir,
            records=[],
            selected=None,
            raw_responses=raw_responses,
            fallback_reason=str(exc),
            top_k=max(1, runtime.graph_top_k),
        )
        return result


def validate_graph_plan(
    graph: GeneratedGraphPlan,
    options: GraphValidationOptions,
) -> GraphValidationResult:
    """Validate a generated temporal DAG candidate."""
    errors: list[str] = []
    warnings: list[str] = []
    if graph.graph_type != "temporal_dag":
        errors.append("graph_type must be temporal_dag")
    if graph.n_agents != options.n_agents:
        errors.append(
            f"n_agents mismatch: graph={graph.n_agents} expected={options.n_agents}"
        )
    if not graph.steps:
        errors.append("graph must contain at least one step")
    if len(graph.steps) > options.max_steps:
        errors.append(f"graph exceeds max_steps={options.max_steps}")
    total_messages = sum(len(step.edges) for step in graph.steps)
    if total_messages > options.max_messages:
        errors.append(f"graph exceeds max_messages={options.max_messages}")
    final_receivers: set[int] = set()
    for step_idx, step in enumerate(graph.steps):
        seen: set[tuple[int, int]] = set()
        fan_in: Counter[int] = Counter()
        for src, dst in step.edges:
            edge = (int(src), int(dst))
            if src == dst:
                errors.append(f"step {step_idx} contains self-loop {edge}")
            if src < 0 or dst < 0 or src >= options.n_agents or dst >= options.n_agents:
                errors.append(f"step {step_idx} contains invalid agent id {edge}")
            if edge in seen:
                warnings.append(f"step {step_idx} contains duplicate edge {edge}")
            seen.add(edge)
            fan_in[dst] += 1
            final_receivers.add(dst)
        overloaded = [
            receiver
            for receiver, count in fan_in.items()
            if count > options.max_receiver_fan_in
        ]
        if overloaded:
            errors.append(
                f"step {step_idx} exceeds max_receiver_fan_in for {overloaded}"
            )
    if not final_receivers:
        errors.append("graph has no receiver / answer holder")
    if graph.selected_primary is not None:
        if graph.selected_primary < 0 or graph.selected_primary >= options.n_agents:
            errors.append("selected_primary must be a valid agent id")
    else:
        warnings.append("selected_primary missing")
    if graph.selected_primary is not None and final_receivers:
        _add_reachability_warnings(graph, warnings)
    return GraphValidationResult(valid=not errors, errors=errors, warnings=warnings)


def repair_graph_plan(
    graph: GeneratedGraphPlan,
    options: GraphValidationOptions,
) -> tuple[GeneratedGraphPlan, list[str]]:
    """Apply deterministic repair to common graph-generation mistakes."""
    notes: list[str] = []
    repaired_steps: list[GeneratedGraphStep] = []
    message_budget = options.max_messages
    for step_idx, step in enumerate(graph.steps[: options.max_steps]):
        seen: set[tuple[int, int]] = set()
        fan_in: Counter[int] = Counter()
        edges: list[tuple[int, int]] = []
        for src, dst in step.edges:
            edge = (int(src), int(dst))
            if src == dst:
                notes.append(f"removed self-loop {edge} at step {step_idx}")
                continue
            if src < 0 or dst < 0 or src >= options.n_agents or dst >= options.n_agents:
                notes.append(f"removed invalid edge {edge} at step {step_idx}")
                continue
            if edge in seen:
                notes.append(f"deduped edge {edge} at step {step_idx}")
                continue
            if fan_in[dst] >= options.max_receiver_fan_in:
                notes.append(f"removed fan-in overflow edge {edge} at step {step_idx}")
                continue
            if message_budget <= 0:
                notes.append("trimmed edges beyond max_messages")
                continue
            seen.add(edge)
            fan_in[dst] += 1
            edges.append(edge)
            message_budget -= 1
        if edges:
            repaired_steps.append(
                GeneratedGraphStep(
                    description=step.description,
                    edges=edges,
                    operator_hint=step.operator_hint,
                )
            )
    if len(graph.steps) > options.max_steps:
        notes.append(f"trimmed steps beyond max_steps={options.max_steps}")
    selected = graph.selected_primary
    final_receivers = [
        dst for step in repaired_steps for _src, dst in step.edges
    ]
    if selected is None or selected < 0 or selected >= options.n_agents:
        selected = final_receivers[-1] if final_receivers else None
        notes.append(f"repaired selected_primary={selected}")
    return (
        graph.model_copy(
            update={
                "n_agents": options.n_agents,
                "steps": repaired_steps,
                "selected_primary": selected,
            }
        ),
        notes,
    )


def compile_generated_graph(
    graph: GeneratedGraphPlan,
    options: GraphValidationOptions,
) -> ProtocolGraphSpec:
    """Compile a validated generated graph to ProtocolGraphSpec."""
    validation = validate_graph_plan(graph, options)
    if not validation.valid:
        raise ValueError("; ".join(validation.errors))
    spec = ProtocolGraphSpec(
        name=graph.name,
        n_agents=options.n_agents,
        steps=[
            ProtocolStepSpec(
                transmissions=step.edges,
                description=step.description or f"{graph.name}: step {idx}",
                operator=step.operator_hint or "llm_generated",
            )
            for idx, step in enumerate(graph.steps)
        ],
        operators=["llm_generate_dag"],
        metadata={
            "graph_type": graph.graph_type,
            "generated_graph": True,
            "candidate_id": graph.candidate_id,
            "selected_primary": graph.selected_primary,
            "max_steps": options.max_steps,
            "max_messages": options.max_messages,
            "max_receiver_fan_in": options.max_receiver_fan_in,
            "fallback_topology": graph.fallback_topology,
        },
    )
    return spec.model_copy(
        update={
            "metadata": {
                **spec.metadata,
                **protocol_metadata_with_fingerprint(spec),
            }
        }
    )


